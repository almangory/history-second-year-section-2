import { GoogleGenAI } from "@google/genai";

export default async function handler(req: any, res: any) {
  // Allow POST requests only
  if (req.method !== "POST") {
    return res.status(405).json({ error: "Method not allowed. Use POST." });
  }

  try {
    const { message, history } = req.body || {};

    if (!message || typeof message !== "string" || !message.trim()) {
      return res.status(400).json({ error: "الرجاء إدخال نص السؤال." });
    }

    if (message.length > 500) {
      return res.status(400).json({ error: "نص السؤال طويل جداً، يرجى كتابة سؤال مختصر (أقل من 500 حرف)." });
    }

    const isKeyAvailable = !!process.env.GEMINI_API_KEY && process.env.GEMINI_API_KEY !== "MY_GEMINI_API_KEY";

    if (!isKeyAvailable) {
      // Local fallback responses for Grade 6 history curriculum
      const defaultReplies: Record<string, string> = {
        "أهلاً": "أهلاً بك يا بطل! أنا معلم التاريخ الذكي الخاص بك. اسألني عن أي حدث في كتاب التاريخ للصف السادس، مثل غزو السودان، أو بناء بغداد العبّاسية، أو رحلة حج منسا موسى ملك مالي!",
        "مرحبا": "أهلاً بك يا بطل! أنا معلم التاريخ الذكي الخاص بك. اسألني عن أي حدث في كتاب التاريخ للصف السادس، مثل غزو السودان، أو بناء بغداد العبّاسية، أو رحلة حج منسا موسى ملك مالي!",
      };
      const textLower = message.trim().toLowerCase();
      let reply = "أنا معلم التاريخ الذكي لبلدنا وممالكنا الإفريقية الحبيبة. حالياً أعمل في الوضع المحلي الفوري. إسألني عن: 'مقتل إسماعيل باشا'، 'بناء بغداد'، 'منسا موسى'، أو 'حقوق المواطنة' وسأجيبك فوراً!";

      if (textLower.includes("إسماعيل") || textLower.includes("نمر") || textLower.includes("حرق")) {
        reply = "الملك نمر هو ملك شندي الذي ضاق ذرعاً بإهانات وقسوة إسماعيل باشا (ابن محمد علي باشا) وفرضه للضرائب الباهظة. فاستدرجه عام 1822م وقام بحرقه حياً في ديوانه بعد محاصرته بنيران القش والتبن. مما دفع الدفتدار لشن حملات انتقامية دموية قاسية على الأهالي.";
      } else if (textLower.includes("بغداد") || textLower.includes("المنصور") || textLower.includes("دائري")) {
        reply = "تأسست بغداد الدائرية عام 145هـ (762م) بأمر من الخليفة العباسي الثاني أبو جعفر المنصور (المؤسس الحقيقي للدولة العباسية). اختار موقعها الحيوي على نهر دجلة وصممها بشكل دائري عظيم لتسهيل الدفاع عنها وجعل لها 4 أبواب (الشام، الكوفة، البصرة، خراسان) وبسط قصر الذهب والمسجد بمركزها.";
      } else if (textLower.includes("موسى") || textLower.includes("منسا") || textLower.includes("مالي")) {
        reply = "الملك منسا موسى هو أعظم ملوك إمبراطورية مالي الإسلامية بغرب إفريقيا في القرن 14م. يشتهر برحلته الأسطورية للحج عام 1324م التي وزع فيها أطناناً من الذهب النقي بمصر ومكة مما تسبب في خفض قيمة الذهب لسنوات، وجلب معه علماء لتطوير تيمبكتو عاصمة العلم واللغة العربية.";
      } else if (textLower.includes("مواطن") || textLower.includes("أركان") || textLower.includes("حقوق") || textLower.includes("واجبات")) {
        reply = "سؤال رائع! أركان الدولة الأربعة هي: الشعب، الأرض، الحكومة، والدستور والقوانين. كمواطنين سودانيين صالحين، لدينا حقوق (كالحياة الكريمة والتعليم والصحة والعمل) وواجبات (كاحترام القوانين، محبة الدفاع العسكري، صيانة الممتلكات والبيئة).";
      } else if (defaultReplies[textLower]) {
        reply = defaultReplies[textLower];
      }

      return res.status(200).json({ text: reply });
    }

    const ai = new GoogleGenAI({
      apiKey: process.env.GEMINI_API_KEY,
      httpOptions: {
        headers: {
          "User-Agent": "aistudio-build",
        },
      },
    });

    const systemInstruction = 
      `أنت "الأستاذ طارق" — المعلم والمؤرخ الذكي المشوق والمحبوب لطلاب المرحلة الثانوية لمادة تاريخ الصف الثاني ثانوي في السودان (المركز القومي للمناهج والبحث التربوي - بخت الرضا).
      تتحدث باللغة العربية الفصيحة الواضحة بأسلوب أكاديمي مشجع وراقٍ يناسب نضج طلاب المرحلة الثانوية، وتخاطب الطالب بـ "عزيزي الطالب" أو "باحث التاريخ" أو "زميلي المؤرخ".
      تجيب بحدود 3 إلى 5 أسطر وتقدم تحليلاً تاريخياً دقيقاً ومرتباً زمنياً يرتكز حصراً على منهج التاريخ للصف الثاني ثانوي المعتمد:
      - الوحدة الأولى: تاريخ السودان تحت الحكم التركي المصري (1820م - 1885م) (أسباب الغزو، سقوط سنار ونهاية الفونج، معركتا كورتي وبارا، استشهاد إسماعيل باشا حرقاً بشندي على يد المك نمر، النظام الإداري والحكمدارية، السياسة الاقتصادية واحتكار التجارة، مدرسة الخرطوم الابتدائية 1853م بإدارة رفاعة الطهطاوي، ومقاومة السودانيين وثورة ود طه).
      - الوحدة الثانية: لمحات من تاريخ السودان الحديث والمعاصر (1955م - 1985م) (تمرد توريت أغسطس 1955م، إعلان الاستقلال من داخل البرلمان 19 ديسمبر 1955م ورفع العلم 1 يناير 1956م، الحكم العسكري الأول بقيادة إبراهيم عبود 1958-1964م، حادثة القرشي واندلاع ثورة أكتوبر 1964م وجبهة الهيئات، الديمقراطية الثانية، وحكم مايو 1969-1985م بقيادة جعفر نميري واتفاقية أديس أبابا 1972م، وانتفاضة أبريل 1985م).
      - الوحدة الثالثة: تاريخ أوروبا الحديث (ملامح العصور الوسطى والإقطاع، عصر النهضة بإيطاليا واختراع جوتنبرغ للطباعة، حركة الكشوف الجغرافية ودوافعها الاقتصادية والدينية، الثورة الفرنسية 1789م وسقوط الباستيل وإعدام لويس السادس عشر وعهد الإرهاب وحكومة الإدارة، الثورة الصناعية ببريطانيا وقوة الآلة البخارية، الوحدة الإيطالية 1815-1870م ودور كافور وغاريبالدي، والوحدة الألمانية 1815-1871م ودور بسمارك وسياسة الحديد والدم).
      - الوحدة الرابعة: الصراع الأوروبي والتوسع الاستعماري (الحرب العالمية الأولى 1914-1918م واغتيال الأرشيدوق بسراييفو وعصبة الأمم، والحرب العالمية الثانية 1939-1945م ومعارك العلمين وهيروشيما وهيئة الأمم المتحدة).
      قاعدة صارمة للغاية: يجب أن ترفض الإجابة على أي أسئلة خارجة عن هذا المنهج التاريخي، وتوجه الطالب بلطف وكياسة أكاديمية للتركيز على استيعاب وحدات تاريخ الصف الثاني ثانوي، مع تقديم شروحات تاريخية تحليلية موثقة.`;

    const contents = history && Array.isArray(history) 
      ? [...history, { role: "user", parts: [{ text: message }] }] 
      : [{ role: "user", parts: [{ text: message }] }];

    const response = await ai.models.generateContent({
      model: "gemini-2.5-flash",
      contents: contents,
      config: {
        systemInstruction: systemInstruction,
        temperature: 0.7,
      }
    });

    return res.status(200).json({ text: response.text });
  } catch (error: any) {
    console.error("Gemini API Error in /api/chat:", error);
    return res.status(500).json({ error: "حدث خطأ أثناء التواصل مع المعلم الذكي. الرجاء المحاولة مرة أخرى." });
  }
}
